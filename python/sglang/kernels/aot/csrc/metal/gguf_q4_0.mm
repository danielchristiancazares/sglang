// Reuse each activation fragment across two Q4_K output rows. This mapping
// adapts kernel_mul_mv_q4_K_f32_impl from ggml-org/llama.cpp's
// ggml/src/ggml-metal/ggml-metal.metal at
// 749f688fcaa4c472ec034b08cb8a907c45cfaa02; see THIRDPARTYNOTICES.txt.
kernel void q4_K_batch_1_rows2(
        device const block_q4_K * weights,
        device const float * input,
        device float * output,
        constant Q4Args & args,
        uint group [[threadgroup_position_in_grid]],
        ushort lane [[thread_index_in_simdgroup]],
        ushort simd_id [[simdgroup_index_in_threadgroup]]) {
    constexpr ushort rows_per_simdgroup = 2;
    constexpr ushort simdgroups = 2;
    constexpr ushort words_per_block = 72;
    constexpr ushort scale_mask = 0x3f3f;
    constexpr ushort low_mask = 0x0f0f;
    constexpr ushort high_mask = 0xc0c0;

    const ushort ix = lane / 8;
    const ushort it = lane % 8;
    const ushort iq = it / 4;
    const ushort ir = it % 4;
    const uint first_row =
        (group * simdgroups + simd_id) * rows_per_simdgroup;
    device const block_q4_K * row_weights =
        weights + first_row * args.blocks_per_row;
    device const float * input_fragment =
        input + ix * 256 + 64 * iq + 8 * ir;
    const uint row_stride_words = args.blocks_per_row * words_per_block;

    float low_values[16];
    float high_values[16];
    float sums[rows_per_simdgroup] = {0.0f};
    ushort unpacked_scales[4];
    thread const uchar * scale_bytes =
        reinterpret_cast<thread const uchar *>(unpacked_scales);

    for (uint block_index = ix;
         block_index < args.blocks_per_row;
         block_index += 4) {
        float4 input_sums = float4(0.0f);
#pragma unroll
        for (ushort i = 0; i < 8; ++i) {
            low_values[i] = input_fragment[i];
            input_sums[0] += low_values[i];
            low_values[i + 8] = input_fragment[i + 32];
            input_sums[1] += low_values[i + 8];
            high_values[i] = input_fragment[i + 128];
            input_sums[2] += high_values[i];
            high_values[i + 8] = input_fragment[i + 160];
            input_sums[3] += high_values[i + 8];
        }

        device const ushort * scales =
            reinterpret_cast<device const ushort *>(
                row_weights[block_index].scales) + iq;
        device const ushort * quants =
            reinterpret_cast<device const ushort *>(
                row_weights[block_index].qs) + 16 * iq + 4 * ir;
        device const half * deltas = &row_weights[block_index].d;

#pragma unroll
        for (ushort row_offset = 0;
             row_offset < rows_per_simdgroup;
             ++row_offset) {
            unpacked_scales[0] = scales[0] & scale_mask;
            unpacked_scales[1] = scales[2] & scale_mask;
            unpacked_scales[2] =
                (scales[4] & low_mask) |
                ((scales[0] & high_mask) >> 2);
            unpacked_scales[3] =
                ((scales[4] >> 4) & low_mask) |
                ((scales[2] & high_mask) >> 2);

            device const ushort * high_quants = quants + 32;
            float4 low_accumulator = float4(0.0f);
            float4 high_accumulator = float4(0.0f);
#pragma unroll
            for (ushort i = 0; i < 4; ++i) {
                low_accumulator[0] +=
                    low_values[2 * i] * float(quants[i] & 0x000f);
                low_accumulator[1] +=
                    low_values[2 * i + 1] * float(quants[i] & 0x0f00);
                low_accumulator[2] +=
                    low_values[2 * i + 8] * float(quants[i] & 0x00f0);
                low_accumulator[3] +=
                    low_values[2 * i + 9] * float(quants[i] & 0xf000);
                high_accumulator[0] +=
                    high_values[2 * i] * float(high_quants[i] & 0x000f);
                high_accumulator[1] +=
                    high_values[2 * i + 1] *
                    float(high_quants[i] & 0x0f00);
                high_accumulator[2] +=
                    high_values[2 * i + 8] *
                    float(high_quants[i] & 0x00f0);
                high_accumulator[3] +=
                    high_values[2 * i + 9] *
                    float(high_quants[i] & 0xf000);
            }

            sums[row_offset] += deltas[0] * (
                (low_accumulator[0] + low_accumulator[1] / 256.0f) *
                    float(scale_bytes[0]) +
                (low_accumulator[2] + low_accumulator[3] / 256.0f) *
                    float(scale_bytes[1]) / 16.0f +
                (high_accumulator[0] + high_accumulator[1] / 256.0f) *
                    float(scale_bytes[4]) +
                (high_accumulator[2] + high_accumulator[3] / 256.0f) *
                    float(scale_bytes[5]) / 16.0f) -
                deltas[1] * (
                    input_sums[0] * float(scale_bytes[2]) +
                    input_sums[1] * float(scale_bytes[3]) +
                    input_sums[2] * float(scale_bytes[6]) +
                    input_sums[3] * float(scale_bytes[7]));

            quants += row_stride_words;
            scales += row_stride_words;
            deltas += row_stride_words;
        }

        input_fragment += 4 * 256;
    }

#pragma unroll
    for (ushort row_offset = 0;
         row_offset < rows_per_simdgroup;
         ++row_offset) {
        const float sum = simd_sum(sums[row_offset]);
        if (lane == 0) {
            output[first_row + row_offset] = sum;
        }
    }
}

#if SGLANG_SIMDGROUP_MATRIX
inline void dequant_iq2_xxs_16(
        device const block_iq2_xxs * block,
        short chunk16,
        thread float4x4 & values) {
    const uint group32 = uint(chunk16) / 2;
    const uint half32 = uint(chunk16) & 1;
    device const ushort * q2 = block->qs + 4 * group32;
    const uint packed_grids = uint(q2[0]) | (uint(q2[1]) << 16);
    const uint packed_aux = uint(q2[2]) | (uint(q2[3]) << 16);
    const float scale = float(block->d) *
        (0.5f + float(packed_aux >> 28)) * 0.25f;

#pragma unroll
    for (ushort grid_group = 0; grid_group < 2; ++grid_group) {
        const uint source_group = 2 * half32 + grid_group;
        const uint grid_index =
            (packed_grids >> (8 * source_group)) & 0xff;
        const ulong grid = kIQ2XXSGrid[grid_index];
        const uchar signs =
            kIQ2Signs[(packed_aux >> (7 * source_group)) & 127];
#pragma unroll
        for (ushort lane = 0; lane < 8; ++lane) {
            const ushort index = 8 * grid_group + lane;
            const float magnitude =
                float((grid >> (8 * lane)) & 0xfful);
            values[index / 4][index & 3] = scale * magnitude *
                ((signs & (1u << lane)) != 0 ? -1.0f : 1.0f);
        }
    }
}

// Large prefills reuse one dequantized 64x32 weight tile across 32 input
// rows. The 4-SIMD-group layout follows kernel_mul_mm_iq2_xxs_f32 from
// ggml-org/llama.cpp@749f688fcaa4c472ec034b08cb8a907c45cfaa02;
// see THIRDPARTYNOTICES.txt. Small-batch decode keeps its dedicated kernels.
kernel void iq2_xxs_large_batch(
        device const block_iq2_xxs * weights,
        device const float * input,
        device float * output,
        constant Q4Args & args,
        threadgroup uchar * shared [[threadgroup(0)]],
        uint2 group [[threadgroup_position_in_grid]],
        ushort tid [[thread_index_in_threadgroup]],
        ushort simd_id [[simdgroup_index_in_threadgroup]]) {
    constexpr ushort output_tile = 64;
    constexpr ushort batch_tile = 32;
    constexpr ushort k_tile = 32;
    constexpr ushort weight_chunks = k_tile / 16;
    constexpr ushort input_chunks = k_tile / 8;

    threadgroup float * staged_weights =
        reinterpret_cast<threadgroup float *>(shared);
    threadgroup float * staged_input =
        reinterpret_cast<threadgroup float *>(shared + 8192);

    const uint output_start = group.x * output_tile;
    const uint batch_start = group.y * batch_tile;
    const ushort valid_outputs = ushort(min(
        uint(output_tile), args.output_size - output_start));
    const ushort valid_batches = ushort(min(
        uint(batch_tile), args.batch_size - batch_start));
    const ushort local_output = ushort(min(
        uint(tid / weight_chunks), uint(valid_outputs - 1)));
    const ushort local_batch = ushort(min(
        uint(tid / input_chunks), uint(valid_batches - 1)));
    const ushort initial_chunk = tid % weight_chunks;
    short chunk16 = short(initial_chunk);

    device const block_iq2_xxs * weight_block =
        weights + (output_start + local_output) * args.blocks_per_row;
    const ushort input_column = 8 * (tid % input_chunks);
    device const float * input_row =
        input + (batch_start + local_batch) * args.input_size + input_column;

    simdgroup_float8x8 weight_fragments[4];
    simdgroup_float8x8 input_fragments[2];
    simdgroup_float8x8 accumulators[8];
#pragma unroll
    for (ushort i = 0; i < 8; ++i) {
        accumulators[i] = make_filled_simdgroup_matrix<float, 8>(0.0f);
    }

    for (uint loop_k = 0; loop_k < args.input_size; loop_k += k_tile) {
        float4x4 dequantized;
        dequant_iq2_xxs_16(weight_block, chunk16, dequantized);

        // Protect the preceding iteration's fragment loads before this
        // iteration overwrites the shared tiles.
        threadgroup_barrier(mem_flags::mem_threadgroup);

#pragma unroll
        for (ushort i = 0; i < 16; ++i) {
            const ushort matrix_x = 2 * initial_chunk + i / 8;
            const ushort matrix_y = (tid / weight_chunks) / 8;
            const ushort matrix_block = 8 * matrix_x + matrix_y;
            const ushort matrix_row = i & 7;
            const ushort matrix_column = (tid / weight_chunks) & 7;
            staged_weights[
                64 * matrix_block + 8 * matrix_row + matrix_column] =
                dequantized[i / 4][i & 3];
        }

#pragma unroll
        for (ushort i = 0; i < 8; ++i) {
            const ushort matrix_x = tid % input_chunks;
            const ushort matrix_y = (tid / input_chunks) / 8;
            const ushort matrix_block = 4 * matrix_x + matrix_y;
            const ushort matrix_row = (tid / input_chunks) & 7;
            staged_input[
                64 * matrix_block + 8 * matrix_row + i] =
                input_row[i];
        }

        chunk16 = (chunk16 + 2 < 16) ? chunk16 + 2 : chunk16 % 2;
        if (chunk16 < 2) {
            ++weight_block;
        }
        input_row += k_tile;

        threadgroup_barrier(mem_flags::mem_threadgroup);

        threadgroup const float * weight_tile_ptr =
            staged_weights + 4 * 64 * (simd_id & 1);
        threadgroup const float * input_tile_ptr =
            staged_input + 2 * 64 * (simd_id >> 1);

#pragma unroll
        for (ushort k_step = 0; k_step < k_tile / 8; ++k_step) {
            simdgroup_barrier(mem_flags::mem_none);
#pragma unroll
            for (ushort i = 0; i < 4; ++i) {
                simdgroup_load(
                    weight_fragments[i], weight_tile_ptr + 64 * i,
                    8, 0, false);
            }
            simdgroup_barrier(mem_flags::mem_none);
#pragma unroll
            for (ushort i = 0; i < 2; ++i) {
                simdgroup_load(
                    input_fragments[i], input_tile_ptr + 64 * i,
                    8, 0, false);
            }
            simdgroup_barrier(mem_flags::mem_none);
#pragma unroll
            for (ushort i = 0; i < 8; ++i) {
                simdgroup_multiply_accumulate(
                    accumulators[i], input_fragments[i / 4],
                    weight_fragments[i & 3], accumulators[i]);
            }
            weight_tile_ptr += 8 * 64;
            input_tile_ptr += 4 * 64;
        }
    }

    if (valid_outputs == output_tile && valid_batches == batch_tile) {
        device float * tile_output = output +
            output_start + 32 * (simd_id & 1) +
            (batch_start + 16 * (simd_id >> 1)) * args.output_size;
#pragma unroll
        for (ushort i = 0; i < 8; ++i) {
            simdgroup_store(
                accumulators[i],
                tile_output + 8 * (i & 3) +
                    8 * args.output_size * (i / 4),
                args.output_size, 0, false);
        }
        return;
    }

    threadgroup_barrier(mem_flags::mem_threadgroup);
    threadgroup float * tail_output =
        reinterpret_cast<threadgroup float *>(shared) +
        32 * (simd_id & 1) + 16 * (simd_id >> 1) * output_tile;
#pragma unroll
    for (ushort i = 0; i < 8; ++i) {
        simdgroup_store(
            accumulators[i],
            tail_output + 8 * (i & 3) + 8 * output_tile * (i / 4),
            output_tile, 0, false);
    }
    threadgroup_barrier(mem_flags::mem_threadgroup);

    if (simd_id == 0) {
        for (ushort batch = tid; batch < valid_batches; batch += batch_tile) {
            device float * destination = output +
                output_start + (batch_start + batch) * args.output_size;
            threadgroup float * source =
                reinterpret_cast<threadgroup float *>(shared) +
                batch * output_tile;
            device float4 * destination4 =
                reinterpret_cast<device float4 *>(destination);
            threadgroup float4 * source4 =
                reinterpret_cast<threadgroup float4 *>(source);
            ushort output_index = 0;
            for (; output_index < valid_outputs / 4; ++output_index) {
                destination4[output_index] = source4[output_index];
            }
            output_index *= 4;
            for (; output_index < valid_outputs; ++output_index) {
                destination[output_index] = source[output_index];
            }
        }
    }
}
#endif

// Batch-one IQ2_XXS matrix-vector products reuse each 32-value input chunk
// across four output rows. Staging the compact lookup tables once per
// threadgroup also turns the four random grid/sign lookups per row and chunk
// into threadgroup-memory reads. This mapping adapts
// kernel_mul_mv_iq2_xxs_f32_impl from ggml-org/llama.cpp's
// ggml/src/ggml-metal/ggml-metal.metal at
// 749f688fcaa4c472ec034b08cb8a907c45cfaa02; see THIRDPARTYNOTICES.txt.
kernel void iq2_xxs_batch_1(
        device const block_iq2_xxs * weights,
        device const float * input,
        device float * output,
        constant Q4Args & args,
        uint group [[threadgroup_position_in_grid]],
        ushort lane [[thread_index_in_simdgroup]],
        ushort simd_id [[simdgroup_index_in_threadgroup]]) {
    constexpr ushort rows_per_simdgroup = 4;
    constexpr ushort simdgroups = 2;
    threadgroup ulong grid_lut[256];
    threadgroup uchar sign_lut[128];

    const uint local_thread = simd_id * 32 + lane;
#pragma unroll
    for (ushort i = 0; i < 4; ++i) {
        const uint index = local_thread + i * 64;
        grid_lut[index] = kIQ2XXSGrid[index];
    }
#pragma unroll
    for (ushort i = 0; i < 2; ++i) {
        const uint index = local_thread + i * 64;
        sign_lut[index] = kIQ2Signs[index];
    }
    threadgroup_barrier(mem_flags::mem_threadgroup);
    const uint first_row =
        (group * simdgroups + simd_id) * rows_per_simdgroup;
    const uint chunks_per_row = args.blocks_per_row * 8;
    float sums[rows_per_simdgroup] = {0.0f};

    if (first_row < args.output_size) {
        for (uint chunk = lane; chunk < chunks_per_row; chunk += 32) {
            float input_chunk[32];
#pragma unroll
            for (ushort i = 0; i < 32; ++i) {
                input_chunk[i] = input[chunk * 32 + i];
            }

            const uint block_index = chunk / 8;
            const uint group32 = chunk & 7;
#pragma unroll
            for (ushort row_offset = 0;
                 row_offset < rows_per_simdgroup;
                 ++row_offset) {
                const uint row = first_row + row_offset;
                if (row >= args.output_size) {
                    continue;
                }
                device const block_iq2_xxs * block =
                    weights + row * args.blocks_per_row + block_index;
                device const ushort * q2 = block->qs + 4 * group32;
                const uint packed_grids =
                    uint(q2[0]) | (uint(q2[1]) << 16);
                const uint packed_aux =
                    uint(q2[2]) | (uint(q2[3]) << 16);
                const float scale = float(block->d) *
                    (0.5f + float(packed_aux >> 28));
                float chunk_sum = 0.0f;
#pragma unroll
                for (ushort grid_group = 0; grid_group < 4; ++grid_group) {
                    const uint grid_index =
                        (packed_grids >> (8 * grid_group)) & 0xff;
                    const threadgroup uchar * grid =
                        (const threadgroup uchar *)(grid_lut + grid_index);
                    const uchar signs =
                        sign_lut[(packed_aux >> (7 * grid_group)) & 127];
#pragma unroll
                    for (ushort j = 0; j < 8; ++j) {
                        chunk_sum += input_chunk[8 * grid_group + j] *
                            float(grid[j]) *
                            ((signs & (1u << j)) ? -1.0f : 1.0f);
                    }
                }
                sums[row_offset] += scale * chunk_sum;
            }
        }
    }

#pragma unroll
    for (ushort row_offset = 0;
         row_offset < rows_per_simdgroup;
         ++row_offset) {
        const float sum = simd_sum(sums[row_offset]);
        const uint row = first_row + row_offset;
        if (lane == 0 && row < args.output_size) {
            output[row] = sum * 0.25f;
        }
    }
}

// Batch-one decode is dominated by matrix-vector products. Process four rows
// per SIMD group so each input vector load feeds four independent IQ1_M rows.
// The row/chunk mapping follows llama.cpp's Metal IQ1_M matvec at
// ggml-org/llama.cpp@749f688fcaa4c472ec034b08cb8a907c45cfaa02.
kernel void iq1_m_batch_1(
        device const block_iq1_m * weights,
        device const float * input,
        device float * output,
        constant Q4Args & args,
        uint group [[threadgroup_position_in_grid]],
        ushort lane [[thread_index_in_simdgroup]],
        ushort simd_id [[simdgroup_index_in_threadgroup]]) {
    constexpr ushort rows_per_simdgroup = 4;
    constexpr ushort simdgroups = 2;
    const uint first_row =
        (group * simdgroups + simd_id) * rows_per_simdgroup;
    const uint chunks_per_row = args.blocks_per_row * 8;
    float sums[rows_per_simdgroup] = {0.0f};

    for (uint chunk = lane; chunk < chunks_per_row; chunk += 32) {
        device const float4 * y =
            reinterpret_cast<device const float4 *>(input + chunk * 32);
        const float4 y0 = y[0];
        const float4 y1 = y[1];
        const float4 y2 = y[2];
        const float4 y3 = y[3];
        const float4 y4 = y[4];
        const float4 y5 = y[5];
        const float4 y6 = y[6];
        const float4 y7 = y[7];
        const float4 ones = float4(1.0f);
        const float4 input_sums = float4(
            dot(y0 + y1, ones),
            dot(y2 + y3, ones),
            dot(y4 + y5, ones),
            dot(y6 + y7, ones));
        const uint block_index = chunk / 8;
        const uint group32 = chunk & 7;

#pragma unroll
        for (ushort row_offset = 0;
             row_offset < rows_per_simdgroup;
             ++row_offset) {
            const uint row = first_row + row_offset;
            if (row >= args.output_size) {
                continue;
            }
            device const block_iq1_m * block =
                weights + row * args.blocks_per_row + block_index;
            device const ushort * scales =
                reinterpret_cast<device const ushort *>(block->scales);
            const ushort scale_bits = (scales[0] >> 12) |
                ((scales[1] >> 8) & 0x00f0) |
                ((scales[2] >> 4) & 0x0f00) |
                (scales[3] & 0xf000);
            const float d = float(as_type<half>(scale_bits));
            device const uchar * qs = block->qs + 4 * group32;
            device const uchar * qh = block->qh + 2 * group32;

            const uchar4 packed0 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[0]) | (uint(qh[0] & 0x07) << 8)]);
            const uchar4 packed1 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[1]) | (uint(qh[0] & 0x70) << 4)]);
            const uchar4 packed2 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[2]) | (uint(qh[1] & 0x07) << 8)]);
            const uchar4 packed3 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[3]) | (uint(qh[1] & 0x70) << 4)]);
            const uchar4 low_mask = uchar4(0x0f);
            const float sum0 =
                dot(y0, float4(packed0 & low_mask)) +
                dot(y1, float4(packed0 >> 4)) +
                dot(y2, float4(packed1 & low_mask)) +
                dot(y3, float4(packed1 >> 4));
            const float sum1 =
                dot(y4, float4(packed2 & low_mask)) +
                dot(y5, float4(packed2 >> 4)) +
                dot(y6, float4(packed3 & low_mask)) +
                dot(y7, float4(packed3 >> 4));
            const float delta0 =
                input_sums[0] * ((qh[0] & 0x08) ? -1.125f : -0.875f) +
                input_sums[1] * ((qh[0] & 0x80) ? -1.125f : -0.875f);
            const float delta1 =
                input_sums[2] * ((qh[1] & 0x08) ? -1.125f : -0.875f) +
                input_sums[3] * ((qh[1] & 0x80) ? -1.125f : -0.875f);
            const uint scale_shift = 6 * (group32 & 1);
            const ushort packed_scales = scales[group32 / 2];
            const float local_scale0 =
                float(2 * ((packed_scales >> scale_shift) & 7) + 1);
            const float local_scale1 =
                float(2 * ((packed_scales >> (scale_shift + 3)) & 7) + 1);
            sums[row_offset] += d * (
                (sum0 + delta0) * local_scale0 +
                (sum1 + delta1) * local_scale1);
        }
    }

#pragma unroll
    for (ushort row_offset = 0;
         row_offset < rows_per_simdgroup;
         ++row_offset) {
        const float sum = simd_sum(sums[row_offset]);
        const uint row = first_row + row_offset;
        if (lane == 0 && row < args.output_size) {
            output[row] = sum;
        }
    }
}

template <ushort BatchTile>
kernel void iq1_m_multi_batch_impl(
        device const block_iq1_m * weights,
        device const float * input,
        device float * output,
        constant Q4Args & args,
        uint2 group [[threadgroup_position_in_grid]],
        ushort lane [[thread_index_in_simdgroup]],
        ushort simd_id [[simdgroup_index_in_threadgroup]]) {
    constexpr ushort simdgroups = 4;
    const uint row = group.x * simdgroups + simd_id;
    const uint batch_start = group.y * BatchTile;
    const bool valid_row = row < args.output_size;
    device const block_iq1_m * row_weights = valid_row
        ? weights + row * args.blocks_per_row : weights;
    const uint chunks_per_row = args.blocks_per_row * 8;
    float sums[BatchTile] = {[0 ... BatchTile - 1] = 0.0f};

    if (valid_row) {
        for (uint chunk = lane; chunk < chunks_per_row; chunk += 32) {
            device const block_iq1_m * block =
                row_weights + chunk / 8;
            const uint group32 = chunk & 7;
            device const ushort * scales =
                reinterpret_cast<device const ushort *>(block->scales);
            const ushort scale_bits = (scales[0] >> 12) |
                ((scales[1] >> 8) & 0x00f0) |
                ((scales[2] >> 4) & 0x0f00) |
                (scales[3] & 0xf000);
            const float d = float(as_type<half>(scale_bits));
            device const uchar * qs = block->qs + 4 * group32;
            device const uchar * qh = block->qh + 2 * group32;
            const uchar4 packed0 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[0]) | (uint(qh[0] & 0x07) << 8)]);
            const uchar4 packed1 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[1]) | (uint(qh[0] & 0x70) << 4)]);
            const uchar4 packed2 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[2]) | (uint(qh[1] & 0x07) << 8)]);
            const uchar4 packed3 = as_type<uchar4>(
                kIQ1SGrid[uint(qs[3]) | (uint(qh[1] & 0x70) << 4)]);
            const uchar4 low_mask = uchar4(0x0f);
            const uint scale_shift = 6 * (group32 & 1);
            const ushort packed_scales = scales[group32 / 2];
            const float local_scale0 =
                d * float(2 * ((packed_scales >> scale_shift) & 7) + 1);
            const float local_scale1 = d * float(
                2 * ((packed_scales >> (scale_shift + 3)) & 7) + 1);

#pragma unroll(BatchTile)
            for (ushort batch = 0; batch < BatchTile; ++batch) {
                const uint batch_index = batch_start + batch;
                if (batch_index >= args.batch_size) {
                    continue;
                }
                device const float4 * y =
                    reinterpret_cast<device const float4 *>(
                        input + batch_index * args.input_size + chunk * 32);
                const float4 y0 = y[0];
                const float4 y1 = y[1];
                const float4 y2 = y[2];
                const float4 y3 = y[3];
                const float4 y4 = y[4];
                const float4 y5 = y[5];
                const float4 y6 = y[6];
                const float4 y7 = y[7];
                const float sum0 =
                    dot(y0, float4(packed0 & low_mask)) +
                    dot(y1, float4(packed0 >> 4)) +
                    dot(y2, float4(packed1 & low_mask)) +
                    dot(y3, float4(packed1 >> 4));
                const float sum1 =
                    dot(y4, float4(packed2 & low_mask)) +
                    dot(y5, float4(packed2 >> 4)) +
                    dot(y6, float4(packed3 & low_mask)) +
                    dot(y7, float4(packed3 >> 4));
                const float4 ones = float4(1.0f);
                const float delta0 =
                    dot(y0 + y1, ones) *
                        ((qh[0] & 0x08) ? -1.125f : -0.875f) +
                    dot(y2 + y3, ones) *
                        ((qh[0] & 0x80) ? -1.125f : -0.875f);
                const float delta1 =
                    dot(y4 + y5, ones) *
                        ((qh[1] & 0x08) ? -1.125f : -0.875f) +
                    dot(y6 + y7, ones) *
                        ((qh[1] & 0x80) ? -1.125f : -0.875f);
                sums[batch] += (sum0 + delta0) * local_scale0 +
                    (sum1 + delta1) * local_scale1;
            }
        }
    }

#pragma unroll(BatchTile)
    for (ushort batch = 0; batch < BatchTile; ++batch) {
        sums[batch] = simd_sum(sums[batch]);
    }
    if (lane == 0 && valid_row) {
#pragma unroll(BatchTile)
        for (ushort batch = 0; batch < BatchTile; ++batch) {
            const uint batch_index = batch_start + batch;
            if (batch_index < args.batch_size) {
                output[batch_index * args.output_size + row] = sums[batch];
            }
        }
    }
}

