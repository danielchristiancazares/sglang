torch::Tensor decode_gqa(
    const torch::Tensor & query,
    const torch::Tensor & key,
    const torch::Tensor & value,
    const torch::Tensor & key_cache,
    const torch::Tensor & value_cache,
    const torch::Tensor & cache_locations,
    const torch::Tensor & req_to_token,
    const torch::Tensor & req_pool_indices,
    const torch::Tensor & seq_lens,
    double scale) {
    for (const auto & tensor : {query, key, value}) {
        TORCH_CHECK(tensor.device().is_mps(), "decode attention tensors must be on MPS");
        TORCH_CHECK(tensor.scalar_type() == torch::kFloat32,
                    "native Metal decode attention requires float32 query/key/value tensors");
        TORCH_CHECK(tensor.is_contiguous(),
                    "native Metal decode attention tensors must be contiguous");
    }
    for (const auto & tensor : {key_cache, value_cache}) {
        TORCH_CHECK(tensor.device().is_mps(), "decode attention caches must be on MPS");
        TORCH_CHECK(tensor.is_contiguous(),
                    "native Metal decode attention caches must be contiguous");
    }
    TORCH_CHECK(key_cache.scalar_type() == value_cache.scalar_type(),
                "key and value cache dtypes must match");
    const bool cache_is_f32 = key_cache.scalar_type() == torch::kFloat32;
    const bool cache_is_bf16 = key_cache.scalar_type() == torch::kBFloat16;
    TORCH_CHECK(cache_is_f32 || cache_is_bf16,
                "native Metal decode attention requires float32 or bfloat16 caches");
    for (const auto & tensor : {cache_locations, req_pool_indices, seq_lens}) {
        TORCH_CHECK(tensor.device().is_mps(), "decode attention metadata must be on MPS");
        TORCH_CHECK(tensor.scalar_type() == torch::kInt64,
                    "decode attention metadata must have dtype int64");
        TORCH_CHECK(tensor.is_contiguous(),
                    "decode attention metadata must be contiguous");
    }
    TORCH_CHECK(req_to_token.device().is_mps(), "req_to_token must be on MPS");
    TORCH_CHECK(req_to_token.scalar_type() == torch::kInt32,
                "req_to_token must have dtype int32");
    TORCH_CHECK(req_to_token.is_contiguous(), "req_to_token must be contiguous");
    TORCH_CHECK(query.dim() == 3 && key.dim() == 3 && value.dim() == 3,
                "query/key/value must have shape [batch, heads, head_dim]");
    TORCH_CHECK(key_cache.dim() == 3 && value_cache.dim() == 3,
                "KV caches must have shape [slots, heads, head_dim]");
    TORCH_CHECK(key.sizes() == value.sizes(), "key and value shapes must match");
    TORCH_CHECK(key_cache.sizes() == value_cache.sizes(),
                "key and value cache shapes must match");

    const int64_t batch_size = query.size(0);
    const int64_t num_q_heads = query.size(1);
    const int64_t num_kv_heads = key.size(1);
    const int64_t head_dim = query.size(2);
    const int64_t cache_slots = key_cache.size(0);
    TORCH_CHECK(batch_size >= 1 && key.size(0) == batch_size,
                "query/key batch sizes must match");
    TORCH_CHECK(num_q_heads > 0 && num_kv_heads > 0,
                "decode attention requires non-empty query and KV heads");
    TORCH_CHECK(num_q_heads % num_kv_heads == 0,
                "query heads must be divisible by KV heads");
    TORCH_CHECK(key.size(2) == head_dim && key_cache.size(1) == num_kv_heads &&
                    key_cache.size(2) == head_dim,
                "decode attention head geometry does not match the KV cache");
    TORCH_CHECK(head_dim > 0 && head_dim <= 256,
                "native Metal decode attention requires head_dim <= 256");
    TORCH_CHECK(cache_slots > 0,
                "native Metal decode attention requires a non-empty cache");
    TORCH_CHECK(!cache_is_f32 || cache_slots <= 7936,
                "native Metal float32 decode attention supports at most 7936 cache slots");
    TORCH_CHECK(!cache_is_bf16 || head_dim == 256,
                "native Metal bfloat16 decode attention requires head_dim 256");
    TORCH_CHECK(!cache_is_bf16 || cache_slots <= 131073,
                "native Metal bfloat16 decode attention supports at most 131073 cache slots");
    TORCH_CHECK(!cache_is_bf16 ||
                    (batch_size == 1 && num_q_heads == 24 && num_kv_heads == 4),
                "native Metal bfloat16 decode attention requires batch 1, 24 query heads, and 4 KV heads");
    TORCH_CHECK(!cache_is_bf16 || supports_bf16_decode_gqa(),
                "native Metal bfloat16 decode attention requires Apple7+ with 32-lane SIMD groups");
    TORCH_CHECK(req_to_token.dim() == 2,
                "req_to_token must have shape [request_slots, context_length]");
    TORCH_CHECK(cache_locations.numel() >= batch_size &&
                    req_pool_indices.numel() >= batch_size &&
                    seq_lens.numel() >= batch_size,
                "decode attention metadata must cover every batch row");

    auto output = torch::empty_like(query);
    auto buffer_of = [](const torch::Tensor & tensor) {
        return (__bridge id<MTLBuffer>)tensor.storage().data_ptr().get();
    };
    auto offset_of = [](const torch::Tensor & tensor) -> NSUInteger {
        return tensor.storage_offset() * tensor.element_size();
    };

    AttentionArgs args = {
        static_cast<uint32_t>(batch_size),
        static_cast<uint32_t>(num_q_heads),
        static_cast<uint32_t>(num_kv_heads),
        static_cast<uint32_t>(head_dim),
        static_cast<uint32_t>(cache_slots),
        static_cast<uint32_t>(req_to_token.size(0)),
        static_cast<uint32_t>(req_to_token.size(1)),
        static_cast<float>(scale),
    };

    at::mps::MPSStream * stream = at::mps::getCurrentMPSStream();
    Pipelines & p = pipelines();
    dispatch_sync(stream->queue(), ^{
        id<MTLComputeCommandEncoder> encoder = stream->commandEncoder();
        [encoder setComputePipelineState:
            cache_is_bf16 ? p.store_decode_kv_bf16 : p.store_decode_kv];
        [encoder setBuffer:buffer_of(key) offset:offset_of(key) atIndex:0];
        [encoder setBuffer:buffer_of(value) offset:offset_of(value) atIndex:1];
        [encoder setBuffer:buffer_of(key_cache) offset:offset_of(key_cache) atIndex:2];
        [encoder setBuffer:buffer_of(value_cache) offset:offset_of(value_cache) atIndex:3];
        [encoder setBuffer:buffer_of(cache_locations)
                 offset:offset_of(cache_locations) atIndex:4];
        [encoder setBytes:&args length:sizeof(args) atIndex:5];
        const NSUInteger kv_total = batch_size * num_kv_heads * head_dim;
        [encoder dispatchThreads:MTLSizeMake(kv_total, 1, 1)
            threadsPerThreadgroup:MTLSizeMake(256, 1, 1)];
        [encoder memoryBarrierWithScope:MTLBarrierScopeBuffers];

        [encoder setComputePipelineState:
            cache_is_bf16 ? p.decode_gqa_bf16 : p.decode_gqa];
        [encoder setBuffer:buffer_of(query) offset:offset_of(query) atIndex:0];
        [encoder setBuffer:buffer_of(key_cache) offset:offset_of(key_cache) atIndex:1];
        [encoder setBuffer:buffer_of(value_cache) offset:offset_of(value_cache) atIndex:2];
        [encoder setBuffer:buffer_of(req_to_token) offset:offset_of(req_to_token) atIndex:3];
        [encoder setBuffer:buffer_of(req_pool_indices)
                 offset:offset_of(req_pool_indices) atIndex:4];
        [encoder setBuffer:buffer_of(seq_lens) offset:offset_of(seq_lens) atIndex:5];
        [encoder setBuffer:buffer_of(output) offset:offset_of(output) atIndex:6];
        [encoder setBytes:&args length:sizeof(args) atIndex:7];
        const NSUInteger scratch_bytes = cache_is_bf16
            ? (4 * 256 + 8) * sizeof(float)
            : (cache_slots + 256) * sizeof(float);
        [encoder setThreadgroupMemoryLength:scratch_bytes atIndex:0];
        [encoder dispatchThreadgroups:MTLSizeMake(batch_size * num_q_heads, 1, 1)
                    threadsPerThreadgroup:MTLSizeMake(cache_is_bf16 ? 128 : 256,
                                                      1, 1)];
    });
    return output;
}

torch::Tensor extend_gqa_bf16(
    const torch::Tensor & query,
    const torch::Tensor & output,
    const torch::Tensor & key_cache,
    const torch::Tensor & value_cache,
    const torch::Tensor & req_to_token,
    const torch::Tensor & req_pool_indices,
    const torch::Tensor & seq_lens,
    double scale) {
    TORCH_CHECK(query.device().is_mps(),
                "native Metal extend query must be on MPS");
    TORCH_CHECK(query.scalar_type() == torch::kFloat32,
                "native Metal extend query must have dtype float32");
    TORCH_CHECK(query.is_contiguous(),
                "native Metal extend query must be contiguous");
    TORCH_CHECK(query.dim() == 3 && query.size(1) == 24 && query.size(2) == 256,
                "native Metal extend query must have shape [tokens, 24, 256]");
    const int64_t query_tokens = query.size(0);
    TORCH_CHECK(query_tokens >= 1 && query_tokens <= 1024,
                "native Metal extend requires between 1 and 1024 query tokens");
    TORCH_CHECK(output.device().is_mps() &&
                    output.scalar_type() == torch::kFloat32 &&
                    output.is_contiguous() && output.sizes() == query.sizes(),
                "native Metal extend output must match the contiguous float32 MPS query");

    for (const auto & tensor : {key_cache, value_cache}) {
        TORCH_CHECK(tensor.device().is_mps(),
                    "native Metal extend caches must be on MPS");
        TORCH_CHECK(tensor.scalar_type() == torch::kBFloat16,
                    "native Metal extend caches must have dtype bfloat16");
        TORCH_CHECK(tensor.is_contiguous(),
                    "native Metal extend caches must be contiguous");
    }
    TORCH_CHECK(key_cache.dim() == 3 &&
                    key_cache.sizes() == value_cache.sizes(),
                "native Metal extend K/V cache shapes must match");
    TORCH_CHECK(key_cache.size(1) == 4 && key_cache.size(2) == 256,
                "native Metal extend caches must have shape [slots, 4, 256]");
    const int64_t cache_slots = key_cache.size(0);
    TORCH_CHECK(cache_slots >= 1 && cache_slots <= 131073,
                "native Metal extend supports at most 131073 cache slots");

    TORCH_CHECK(req_to_token.device().is_mps() &&
                    req_to_token.scalar_type() == torch::kInt32 &&
                    req_to_token.is_contiguous() && req_to_token.dim() == 2,
                "native Metal extend req_to_token must be contiguous int32 MPS [rows, context]");
    for (const auto & tensor : {req_pool_indices, seq_lens}) {
        TORCH_CHECK(tensor.device().is_mps() &&
                        tensor.scalar_type() == torch::kInt64 &&
                        tensor.is_contiguous() && tensor.numel() == 1,
                    "native Metal extend request metadata must be contiguous int64 MPS data");
    }
    TORCH_CHECK(req_to_token.size(0) >= 1 && req_to_token.size(1) >= 1,
                "native Metal extend requires a non-empty request map");
    TORCH_CHECK(
        static_cast<uint64_t>(req_to_token.size(0)) <=
                std::numeric_limits<uint32_t>::max() &&
            static_cast<uint64_t>(req_to_token.size(1)) <=
                std::numeric_limits<uint32_t>::max(),
        "native Metal extend request-map dimensions must fit uint32");
    const float scale_f32 = static_cast<float>(scale);
    TORCH_CHECK(std::isfinite(scale_f32) && scale_f32 > 0.0f,
                "native Metal extend scale must be finite, positive, and representable as float32");
    TORCH_CHECK(supports_bf16_extend_gqa(),
                "native Metal BF16 extend requires Apple7+ SIMD-group matrices");

    auto buffer_of = [](const torch::Tensor & tensor) {
        return (__bridge id<MTLBuffer>)tensor.storage().data_ptr().get();
    };
    auto offset_of = [](const torch::Tensor & tensor) -> NSUInteger {
        return tensor.storage_offset() * tensor.element_size();
    };
    TORCH_CHECK(buffer_of(output) != buffer_of(query) &&
                    buffer_of(output) != buffer_of(key_cache) &&
                    buffer_of(output) != buffer_of(value_cache) &&
                    buffer_of(output) != buffer_of(req_to_token) &&
                    buffer_of(output) != buffer_of(req_pool_indices) &&
                    buffer_of(output) != buffer_of(seq_lens),
                "native Metal extend output must use distinct storage");

    ExtendAttentionArgs args = {
        static_cast<uint32_t>(query_tokens),
        24,
        4,
        256,
        static_cast<uint32_t>(cache_slots),
        static_cast<uint32_t>(req_to_token.size(0)),
        static_cast<uint32_t>(req_to_token.size(1)),
        scale_f32,
    };

    at::mps::MPSStream * stream = at::mps::getCurrentMPSStream();
    ExtendPipeline & p = extend_pipeline();
    TORCH_CHECK(p.state != nil,
                "native Metal BF16 extend pipeline failed: ", p.error);
    dispatch_sync(stream->queue(), ^{
        id<MTLComputeCommandEncoder> encoder = stream->commandEncoder();
        [encoder setComputePipelineState:p.state];
        [encoder setBuffer:buffer_of(query) offset:offset_of(query) atIndex:0];
        [encoder setBuffer:buffer_of(key_cache)
                 offset:offset_of(key_cache) atIndex:1];
        [encoder setBuffer:buffer_of(value_cache)
                 offset:offset_of(value_cache) atIndex:2];
        [encoder setBuffer:buffer_of(req_to_token)
                 offset:offset_of(req_to_token) atIndex:3];
        [encoder setBuffer:buffer_of(req_pool_indices)
                 offset:offset_of(req_pool_indices) atIndex:4];
        [encoder setBuffer:buffer_of(seq_lens)
                 offset:offset_of(seq_lens) atIndex:5];
        [encoder setBuffer:buffer_of(output) offset:offset_of(output) atIndex:6];
        [encoder setBytes:&args length:sizeof(args) atIndex:7];
        [encoder setThreadgroupMemoryLength:20832 atIndex:0];
        const NSUInteger attention_rows = query_tokens * 6;
        [encoder dispatchThreadgroups:
                     MTLSizeMake((attention_rows + 7) / 8, 4, 1)
                    threadsPerThreadgroup:MTLSizeMake(128, 1, 1)];
    });
    return output;
}

