kernel void silu_and_mul_f32(
        device const float * input,
        device float * output,
        constant NormArgs & args,
        uint index [[thread_position_in_grid]]) {
    const uint total = args.rows * args.columns;
    if (index >= total) {
        return;
    }
    const uint row = index / args.columns;
    const uint column = index - row * args.columns;
    const uint input_row = row * args.columns * 2;
    output[index] = silu_f32(input[input_row + column]) *
        input[input_row + args.columns + column];
}

kernel void gdn_gated_rmsnorm_reorder_f32(
        device const float * input,
        device const float * gate,
        device const float * weight,
        device float * output,
        constant GatedNormArgs & args,
        uint group [[threadgroup_position_in_grid]],
        ushort lane [[thread_index_in_simdgroup]]) {
    const uint batch = group / args.num_v_heads;
    const uint value_head = group - batch * args.num_v_heads;
    if (batch >= args.batch_size) {
        return;
    }
    const uint base = (batch * args.num_v_heads + value_head) * args.head_dim;
    float square_sum = 0.0f;
    for (uint dim = lane; dim < args.head_dim; dim += 32) {
        const float value = input[base + dim];
        square_sum += value * value;
    }
    const float inverse_rms =
        rsqrt(simd_sum(square_sum) / float(args.head_dim) + args.epsilon);
    const uint ratio = args.num_v_heads / args.num_k_heads;
    const uint key_head = value_head / ratio;
    const uint within_group = value_head - key_head * ratio;
    const uint tiled_head = within_group * args.num_k_heads + key_head;
    const uint output_base =
        (batch * args.num_v_heads + tiled_head) * args.head_dim;
    for (uint dim = lane; dim < args.head_dim; dim += 32) {
        output[output_base + dim] = input[base + dim] * inverse_rms * weight[dim]
            * silu_f32(gate[base + dim]);
    }
}

kernel void pack_gdn_inputs_f32(
        device const float * qkvz,
        device const float * ba,
        device float * mixed_qkv,
        device float * gate,
        device float * b_out,
        device float * a_out,
        constant PackArgs & args,
        uint index [[thread_position_in_grid]]) {
    const uint mixed_dim = 2 * args.key_dim + args.value_dim;
    const uint qkvz_dim = mixed_dim + args.value_dim;
    const uint per_batch = mixed_dim + args.value_dim + 2 * args.num_v_heads;
    const uint total = args.batch_size * per_batch;
    if (index >= total) {
        return;
    }
    const uint batch = index / per_batch;
    const uint within = index - batch * per_batch;
    if (within < mixed_dim) {
        mixed_qkv[batch * mixed_dim + within] =
            qkvz[batch * qkvz_dim + within];
    } else if (within < mixed_dim + args.value_dim) {
        const uint offset = within - mixed_dim;
        gate[batch * args.value_dim + offset] =
            qkvz[batch * qkvz_dim + mixed_dim + offset];
    } else if (within < mixed_dim + args.value_dim + args.num_v_heads) {
        const uint offset = within - mixed_dim - args.value_dim;
        b_out[batch * args.num_v_heads + offset] =
            ba[batch * 2 * args.num_v_heads + offset];
    } else {
        const uint offset = within - mixed_dim - args.value_dim - args.num_v_heads;
        a_out[batch * args.num_v_heads + offset] =
            ba[batch * 2 * args.num_v_heads + args.num_v_heads + offset];
    }
}

kernel void normalize_gdn_qk_f32(
        device const float * query,
        device const float * key,
        device float * query_out,
        device float * key_out,
        constant GDNNormArgs & args,
        uint group [[threadgroup_position_in_grid]],
        ushort lane [[thread_index_in_simdgroup]]) {
    const uint token = group / args.num_heads;
    const uint head = group - token * args.num_heads;
    if (token >= args.tokens) {
        return;
    }
    const uint base = (token * args.num_heads + head) * args.head_dim;
    float q_sum = 0.0f;
    float k_sum = 0.0f;
    for (uint dim = lane; dim < args.head_dim; dim += 32) {
        const float q_value = query[base + dim];
        const float k_value = key[base + dim];
        q_sum += q_value * q_value;
        k_sum += k_value * k_value;
    }
    const float q_scale = rsqrt(simd_sum(q_sum) / float(args.head_dim) + 1e-6f)
        / float(args.head_dim);
    const float k_scale = rsqrt(simd_sum(k_sum) / float(args.head_dim) + 1e-6f)
        / sqrt(float(args.head_dim));
    for (uint dim = lane; dim < args.head_dim; dim += 32) {
        query_out[base + dim] = query[base + dim] * q_scale;
        key_out[base + dim] = key[base + dim] * k_scale;
    }
}

kernel void prepare_full_attention_f32(
        device const float * qkv,
        device const float * q_weight,
        device const float * k_weight,
        device const float * cos_sin_cache,
        device const long * positions,
        device float * query_out,
        device float * key_out,
        device float * value_out,
        device float * gate_out,
        constant FullAttentionPrepareArgs & args,
        uint group [[threadgroup_position_in_grid]],
        ushort lane [[thread_index_in_simdgroup]]) {
    const uint heads_per_token = args.num_q_heads + args.num_kv_heads;
    const uint token = group / heads_per_token;
    const uint packed_head = group - token * heads_per_token;
    if (token >= args.tokens) {
        return;
    }
    const bool is_query = packed_head < args.num_q_heads;
    const uint head = is_query ? packed_head : packed_head - args.num_q_heads;
    const uint q_gate_dim = 2 * args.num_q_heads * args.head_dim;
    const uint kv_dim = args.num_kv_heads * args.head_dim;
    const uint qkv_stride = q_gate_dim + 2 * kv_dim;
    const uint source_base = token * qkv_stride +
        (is_query ? head * 2 * args.head_dim
                  : q_gate_dim + head * args.head_dim);
    device const float * norm_weight = is_query ? q_weight : k_weight;

    float square_sum = 0.0f;
    for (uint dim = lane; dim < args.head_dim; dim += 32) {
        const float value = qkv[source_base + dim];
        square_sum += value * value;
    }
    const float inverse_rms =
        rsqrt(simd_sum(square_sum) / float(args.head_dim) + args.epsilon);
    const uint output_base =
        (token * (is_query ? args.num_q_heads : args.num_kv_heads) + head)
        * args.head_dim;
    const uint half_rotary = args.rotary_dim / 2;
    const uint position = uint(positions[token]);
    device const float * cache_row = cos_sin_cache + position * args.rotary_dim;

    for (uint dim = lane; dim < args.head_dim; dim += 32) {
        float output_value;
        if (dim < args.rotary_dim) {
            const uint pair_dim = dim < half_rotary
                ? dim + half_rotary : dim - half_rotary;
            const uint frequency = dim < half_rotary ? dim : dim - half_rotary;
            const float first = qkv[source_base + (dim < half_rotary ? dim : pair_dim)]
                * inverse_rms
                * (1.0f + norm_weight[dim < half_rotary ? dim : pair_dim]);
            const float second = qkv[source_base + (dim < half_rotary ? pair_dim : dim)]
                * inverse_rms
                * (1.0f + norm_weight[dim < half_rotary ? pair_dim : dim]);
            const float cosine = cache_row[frequency];
            const float sine = cache_row[half_rotary + frequency];
            output_value = dim < half_rotary
                ? first * cosine - second * sine
                : second * cosine + first * sine;
        } else {
            output_value = qkv[source_base + dim] * inverse_rms
                * (1.0f + norm_weight[dim]);
        }
        if (is_query) {
            query_out[output_base + dim] = output_value;
            gate_out[output_base + dim] =
                qkv[source_base + args.head_dim + dim];
        } else {
            key_out[output_base + dim] = output_value;
            value_out[output_base + dim] =
                qkv[token * qkv_stride + q_gate_dim + kv_dim
                    + head * args.head_dim + dim];
        }
    }
}

kernel void sigmoid_mul_inplace_f32(
        device float * input,
        device const float * gate,
        constant NormArgs & args,
        uint index [[thread_position_in_grid]]) {
    const uint total = args.rows * args.columns;
    if (index < total) {
        input[index] *= 1.0f / (1.0f + exp(-gate[index]));
    }
}

kernel void causal_conv1d_decode_f32(
        device const float * input,
        device const float * weight,
        device float * state,
        device const int * cache_indices,
        device float * output,
        constant ConvArgs & args,
        uint index [[thread_position_in_grid]]) {
    const uint total = args.batch_size * args.channels;
    if (index >= total) {
        return;
    }
    const uint batch = index / args.channels;
    const uint channel = index % args.channels;
    const int slot = cache_indices[batch];
    if (slot < 0) {
        output[index] = 0.0f;
        return;
    }
    device float * history = state +
        (uint(slot) * args.channels + channel) * 3;
    const float current = input[index];
    const float value = history[0] * weight[channel * 4] +
        history[1] * weight[channel * 4 + 1] +
        history[2] * weight[channel * 4 + 2] +
        current * weight[channel * 4 + 3];
    history[0] = history[1];
    history[1] = history[2];
    history[2] = current;
    output[index] = silu_f32(value);
}

kernel void causal_conv1d_prefill_f32(
        device const float * input,
        device const float * weight,
        device float * state,
        device const int * cache_indices,
        device const int * query_start_loc,
        device const int * has_initial_state,
        device float * output,
        constant ConvArgs & args,
        uint index [[thread_position_in_grid]]) {
    const uint total = args.batch_size * args.channels;
    if (index >= total) {
        return;
    }
    const uint sequence = index / args.channels;
    const uint channel = index % args.channels;
    const int slot = cache_indices[sequence];
    if (slot < 0) {
        return;
    }
    device float * state_row = state +
        (uint(slot) * args.channels + channel) * 3;
    float h0 = has_initial_state[sequence] ? state_row[0] : 0.0f;
    float h1 = has_initial_state[sequence] ? state_row[1] : 0.0f;
    float h2 = has_initial_state[sequence] ? state_row[2] : 0.0f;
    const uint start = uint(query_start_loc[sequence]);
    const uint end = uint(query_start_loc[sequence + 1]);
    for (uint token = start; token < end; ++token) {
        const float current = input[channel * args.num_tokens + token];
        const float value = h0 * weight[channel * 4] +
            h1 * weight[channel * 4 + 1] +
            h2 * weight[channel * 4 + 2] +
            current * weight[channel * 4 + 3];
        output[channel * args.num_tokens + token] = silu_f32(value);
        h0 = h1;
        h1 = h2;
        h2 = current;
    }
    state_row[0] = h0;
    state_row[1] = h1;
    state_row[2] = h2;
}

kernel void gdn_decode_f32(
        device const float * query,
        device const float * key,
        device const float * value,
        device const float * a,
        device const float * b,
        device const float * A_log,
        device const float * dt_bias,
        device float * state,
        device const int * cache_indices,
        device float * output,
        constant GDNArgs & args,
        uint3 group [[threadgroup_position_in_grid]],
        ushort3 local [[thread_position_in_threadgroup]],
        ushort lane [[thread_index_in_simdgroup]]) {
    const uint packed_head = group.z;
    const uint batch = packed_head / args.num_v_heads;
    const uint value_head = packed_head % args.num_v_heads;
    const uint key_head = value_head / (args.num_v_heads / args.num_k_heads);
    const uint value_index = group.y * 4 + local.y;
    if (batch >= args.batch_size || value_index >= args.value_dim) {
        return;
    }

    const uint state_slot = uint(cache_indices[batch]);
    device float * state_row = state +
        ((state_slot * args.num_v_heads + value_head) * args.value_dim + value_index) * args.key_dim;
    device const float * q_row = query +
        (batch * args.num_k_heads + key_head) * args.key_dim;
    device const float * k_row = key +
        (batch * args.num_k_heads + key_head) * args.key_dim;

    const float gate_input = a[batch * args.num_v_heads + value_head] + dt_bias[value_head];
    const float softplus = gate_input > 20.0f
        ? gate_input
        : log(1.0f + exp(gate_input));
    const float decay = exp(-exp(A_log[value_head]) * softplus);
    const float beta = 1.0f /
        (1.0f + exp(-b[batch * args.num_v_heads + value_head]));

    float state_values[4];
    float remembered = 0.0f;
    for (uint index = 0; index < 4; ++index) {
        const uint key_index = lane + index * 32;
        state_values[index] = state_row[key_index] * decay;
        remembered += state_values[index] * k_row[key_index];
    }
    remembered = simd_sum(remembered);

    const float delta =
        (value[(batch * args.num_v_heads + value_head) * args.value_dim + value_index] - remembered) * beta;
    float result = 0.0f;
    for (uint index = 0; index < 4; ++index) {
        const uint key_index = lane + index * 32;
        state_values[index] += k_row[key_index] * delta;
        state_row[key_index] = state_values[index];
        result += state_values[index] * q_row[key_index];
    }
    result = simd_sum(result);
    if (lane == 0) {
        output[(batch * args.num_v_heads + value_head) * args.value_dim + value_index] = result;
    }
}

kernel void gdn_prefill_f32(
        device const float * query,
        device const float * key,
        device const float * value,
        device const float * g,
        device const float * beta,
        device float * state,
        device const int * cache_indices,
        device const int * query_start_loc,
        device float * output,
        constant GDNArgs & args,
        uint3 group [[threadgroup_position_in_grid]],
        ushort3 local [[thread_position_in_threadgroup]],
        ushort lane [[thread_index_in_simdgroup]]) {
    const uint packed_head = group.z;
    const uint sequence = packed_head / args.num_v_heads;
    const uint value_head = packed_head % args.num_v_heads;
    const uint key_head = value_head / (args.num_v_heads / args.num_k_heads);
    const uint value_index = group.y * 4 + local.y;
    if (sequence >= args.batch_size || value_index >= args.value_dim) {
        return;
    }

    const uint start = uint(query_start_loc[sequence]);
    const uint end = uint(query_start_loc[sequence + 1]);
    const uint state_slot = uint(cache_indices[sequence]);
    device float * state_row = state +
        ((state_slot * args.num_v_heads + value_head) * args.value_dim + value_index) * args.key_dim;

    float state_values[4];
    for (uint index = 0; index < 4; ++index) {
        state_values[index] = state_row[lane + index * 32];
    }

    for (uint token = start; token < end; ++token) {
        device const float * q_row = query +
            (token * args.num_k_heads + key_head) * args.key_dim;
        device const float * k_row = key +
            (token * args.num_k_heads + key_head) * args.key_dim;
        const float decay = g[token * args.num_v_heads + value_head];
        const float beta_value = beta[token * args.num_v_heads + value_head];

        float remembered = 0.0f;
        for (uint index = 0; index < 4; ++index) {
            const uint key_index = lane + index * 32;
            state_values[index] *= decay;
            remembered += state_values[index] * k_row[key_index];
        }
        remembered = simd_sum(remembered);

        const float delta =
            (value[(token * args.num_v_heads + value_head) * args.value_dim + value_index] - remembered)
            * beta_value;
        float result = 0.0f;
        for (uint index = 0; index < 4; ++index) {
            const uint key_index = lane + index * 32;
            state_values[index] += k_row[key_index] * delta;
            result += state_values[index] * q_row[key_index];
        }
        result = simd_sum(result);
        if (lane == 0) {
            output[(token * args.num_v_heads + value_head) * args.value_dim + value_index] = result;
        }
    }

    for (uint index = 0; index < 4; ++index) {
        state_row[lane + index * 32] = state_values[index];
    }
}

kernel void store_decode_kv_f32(
        device const float * key,
        device const float * value,
        device float * key_cache,
        device float * value_cache,
        device const long * cache_locations,
        constant AttentionArgs & args,
        uint index [[thread_position_in_grid]]) {
    const uint row_size = args.num_kv_heads * args.head_dim;
    const uint total = args.batch_size * row_size;
    if (index >= total) {
        return;
    }
    const uint batch = index / row_size;
    const long slot = cache_locations[batch];
    if (slot < 0 || ulong(slot) >= ulong(args.cache_slots)) {
        return;
    }
    const uint within = index - batch * row_size;
    const uint cache_index = uint(slot) * row_size + within;
    key_cache[cache_index] = key[index];
    value_cache[cache_index] = value[index];
}

inline float bf16_to_f32(ushort value) {
    return as_type<float>(uint(value) << 16);
}

inline ushort f32_to_bf16_rne(float value) {
    uint bits = as_type<uint>(value);
    if ((bits & 0x7fffffffu) > 0x7f800000u) {
        return ushort((bits >> 16) | 0x0040u);
    }
    bits += 0x7fffu + ((bits >> 16) & 1u);
    return ushort(bits >> 16);
}

#if defined(SGLANG_EXTEND_GQA) && SGLANG_SIMDGROUP_MATRIX && SGLANG_EXTEND_GQA
inline float simd_max_16(float value) {
    value = max(value, simd_shuffle_xor(value, 8));
    value = max(value, simd_shuffle_xor(value, 4));
    value = max(value, simd_shuffle_xor(value, 2));
    return max(value, simd_shuffle_xor(value, 1));
}

inline float simd_sum_16(float value) {
    value += simd_shuffle_xor(value, 8);
    value += simd_shuffle_xor(value, 4);
    value += simd_shuffle_xor(value, 2);
    return value + simd_shuffle_xor(value, 1);
}

// The 8-query/64-cache-token, four-SIMD-group QK/online-softmax/PV tiling
// adapts kernel_flash_attn_ext_impl and OP_FLASH_ATTN_EXT_* geometry from
// ggml-org/llama.cpp commit 749f688fcaa4c472ec034b08cb8a907c45cfaa02.
// SGLang adds paged-cache indirection, GQA/causal mapping, FP32 staging and
// accumulation, and caller-owned output; see THIRDPARTYNOTICES.txt.
// Eight query/head rows share each mapped K/V tile. The complete online-
// softmax state remains in bounded threadgroup storage; no tensor scales with
// query_rows * sequence_length.
kernel void extend_gqa_bf16_tiled_256(
        device const float * query,
        device const ushort * key_cache,
        device const ushort * value_cache,
        device const int * req_to_token,
        device const long * req_pool_indices,
        device const long * seq_lens,
        device float * output,
        constant ExtendAttentionArgs & args,
        threadgroup uchar * shared [[threadgroup(0)]],
        uint2 group [[threadgroup_position_in_grid]],
        ushort tid [[thread_index_in_threadgroup]],
        ushort lane [[thread_index_in_simdgroup]],
        ushort simd_id [[simdgroup_index_in_threadgroup]]) {
    constexpr ushort query_tile = 8;
    constexpr ushort key_tile = 64;
    constexpr ushort heads_per_kv = 6;
    constexpr ushort head_dim = 256;

    threadgroup float * shared_query =
        reinterpret_cast<threadgroup float *>(shared);
    threadgroup float * shared_output = shared_query + query_tile * head_dim;
    threadgroup float * shared_scores = shared_output + query_tile * head_dim;
    threadgroup float * shared_stage = shared_scores + query_tile * key_tile;
    threadgroup int * shared_slots =
        reinterpret_cast<threadgroup int *>(shared_stage + 4 * 8 * 16);
    threadgroup int * shared_runs = shared_slots + key_tile;
    threadgroup float * shared_stats =
        reinterpret_cast<threadgroup float *>(shared_runs + key_tile / 8);

    const uint kv_head = group.y;
    const uint attention_row_start = group.x * query_tile;
    const uint attention_rows = args.query_tokens * heads_per_kv;
    const long raw_seq_len = seq_lens[0];
    const bool metadata_valid = raw_seq_len >= long(args.query_tokens) &&
        ulong(raw_seq_len) <= ulong(args.cache_slots) &&
        ulong(raw_seq_len) <= ulong(args.req_stride);
    const uint seq_len = metadata_valid ? uint(raw_seq_len) : 0;
    const uint prefix_len = metadata_valid
        ? seq_len - args.query_tokens
        : 0;
    const long req_slot = req_pool_indices[0];
    const bool req_valid = metadata_valid &&
        req_slot >= 0 && ulong(req_slot) < ulong(args.req_rows);
    const uint cache_row_size = args.num_kv_heads * head_dim;
    device const bfloat * key_cache_bf16 =
        reinterpret_cast<device const bfloat *>(key_cache);
    device const bfloat * value_cache_bf16 =
        reinterpret_cast<device const bfloat *>(value_cache);
    const uint last_attention_row = min(
        attention_rows - 1, attention_row_start + query_tile - 1);
    const uint group_kv_len = req_valid
        ? min(seq_len, prefix_len + last_attention_row / heads_per_kv + 1)
        : 0;

    for (uint index = tid; index < query_tile * head_dim; index += 128) {
        const uint row = index / head_dim;
        const uint dim = index - row * head_dim;
        const uint attention_row = attention_row_start + row;
        float value = 0.0f;
        if (attention_row < attention_rows) {
            const uint query_token = attention_row / heads_per_kv;
            const uint query_head =
                kv_head * heads_per_kv + attention_row % heads_per_kv;
            value = query[
                (query_token * args.num_q_heads + query_head) * head_dim + dim];
        }
        shared_query[index] = value;
        shared_output[index] = 0.0f;
    }
    if (tid < query_tile) {
        shared_stats[2 * tid] = -INFINITY;
        shared_stats[2 * tid + 1] = 0.0f;
    }
    threadgroup_barrier(mem_flags::mem_threadgroup);

    for (uint key_start = 0; key_start < group_kv_len; key_start += key_tile) {
        int mapped_slot = -1;
        if (tid < key_tile) {
            const uint logical_token = key_start + tid;
            if (req_valid && logical_token < seq_len) {
                const int candidate = req_to_token[
                    ulong(req_slot) * ulong(args.req_stride) + logical_token];
                if (candidate >= 0 && uint(candidate) < args.cache_slots) {
                    mapped_slot = candidate;
                }
            }
            shared_slots[tid] = mapped_slot;

            const ushort run_lane = lane & ~ushort(7);
            const ushort run_offset = lane & ushort(7);
            const int first_slot = simd_shuffle(mapped_slot, run_lane);
            const uint first_slot_u = uint(max(first_slot, 0));
            uint consecutive = first_slot >= 0 &&
                first_slot_u + 7 < args.cache_slots &&
                mapped_slot >= 0 &&
                uint(mapped_slot) == first_slot_u + run_offset;
            consecutive &= simd_shuffle_xor(consecutive, 4);
            consecutive &= simd_shuffle_xor(consecutive, 2);
            consecutive &= simd_shuffle_xor(consecutive, 1);
            if (run_offset == 0) {
                shared_runs[tid / 8] = consecutive ? first_slot : -1;
            }
        }
        threadgroup_barrier(mem_flags::mem_threadgroup);

        simdgroup_float8x8 score_left =
            make_filled_simdgroup_matrix<float, 8>(0.0f);
        simdgroup_float8x8 score_right =
            make_filled_simdgroup_matrix<float, 8>(0.0f);
        threadgroup float * score_stage = shared_stage + simd_id * 8 * 16;
        int key_run_starts[2];
        ulong key_run_offsets[2];
#pragma unroll
        for (ushort key_half = 0; key_half < 2; ++key_half) {
            const int run_start =
                shared_runs[simd_id * 2 + key_half];
            key_run_starts[key_half] = run_start;
            key_run_offsets[key_half] =
                ulong(uint(max(run_start, 0))) * ulong(cache_row_size) +
                kv_head * head_dim;
        }

        for (ushort dim_start = 0; dim_start < head_dim; dim_start += 16) {
            simdgroup_float8x8 query_low;
            simdgroup_float8x8 query_high;
            simdgroup_load(
                query_low, shared_query + dim_start, head_dim, 0, false);
            simdgroup_load(
                query_high, shared_query + dim_start + 8,
                head_dim, 0, false);

#pragma unroll
            for (ushort key_half = 0; key_half < 2; ++key_half) {
                const ushort run_offset = simd_id * 16 + key_half * 8;
                const int run_start = key_run_starts[key_half];
                if (run_start >= 0) {
                    device const bfloat * key_run = key_cache_bf16 +
                        key_run_offsets[key_half] + dim_start;
                    simdgroup_bfloat8x8 key_low;
                    simdgroup_bfloat8x8 key_high;
                    simdgroup_barrier(mem_flags::mem_none);
                    simdgroup_load(
                        key_low, key_run, cache_row_size, 0, true);
                    simdgroup_load(
                        key_high, key_run + 8,
                        cache_row_size, 0, true);
                    simdgroup_barrier(mem_flags::mem_none);
                    if (key_half == 0) {
                        simdgroup_multiply_accumulate(
                            score_left, query_low, key_low, score_left);
                        simdgroup_multiply_accumulate(
                            score_left, query_high, key_high, score_left);
                    } else {
                        simdgroup_multiply_accumulate(
                            score_right, query_low, key_low, score_right);
                        simdgroup_multiply_accumulate(
                            score_right, query_high, key_high, score_right);
                    }
                    continue;
                }

                const ushort key_row = lane / 4;
                const ushort dim_quad = lane & 3;
                const int slot = shared_slots[run_offset + key_row];
#pragma unroll
                for (ushort dim = 0; dim < 4; ++dim) {
                    score_stage[
                        key_row * 16 + dim_quad * 4 + dim] = slot >= 0
                        ? bf16_to_f32(key_cache[
                              ulong(uint(slot)) * ulong(cache_row_size) +
                              kv_head * head_dim + dim_start +
                              dim_quad * 4 + dim])
                        : 0.0f;
                }
                simdgroup_barrier(mem_flags::mem_threadgroup);

                simdgroup_float8x8 key_low;
                simdgroup_float8x8 key_high;
                simdgroup_load(key_low, score_stage, 16, 0, true);
                simdgroup_load(key_high, score_stage + 8, 16, 0, true);
                if (key_half == 0) {
                    simdgroup_multiply_accumulate(
                        score_left, query_low, key_low, score_left);
                    simdgroup_multiply_accumulate(
                        score_left, query_high, key_high, score_left);
                } else {
                    simdgroup_multiply_accumulate(
                        score_right, query_low, key_low, score_right);
                    simdgroup_multiply_accumulate(
                        score_right, query_high, key_high, score_right);
                }
                simdgroup_barrier(mem_flags::mem_threadgroup);
            }
        }

        simdgroup_store(
            score_left, shared_scores + simd_id * 16, key_tile, 0, false);
        simdgroup_store(
            score_right, shared_scores + simd_id * 16 + 8,
            key_tile, 0, false);
        threadgroup_barrier(mem_flags::mem_threadgroup);

        const ushort softmax_row = tid / 16;
        const ushort softmax_lane = tid & 15;
        const uint attention_row = attention_row_start + softmax_row;
        const bool row_valid = attention_row < attention_rows;
        const uint query_token = row_valid
            ? attention_row / heads_per_kv
            : 0;
        const uint causal_limit = row_valid
            ? min(seq_len, prefix_len + query_token + 1)
            : 0;

        float row_max = -INFINITY;
        float scaled_scores[4];
#pragma unroll
        for (ushort index = 0; index < 4; ++index) {
            const ushort key_column = softmax_lane + 16 * index;
            const uint logical_token = key_start + key_column;
            const bool score_valid = row_valid &&
                logical_token < causal_limit &&
                shared_slots[key_column] >= 0;
            const float score = score_valid
                ? shared_scores[softmax_row * key_tile + key_column] * args.scale
                : -INFINITY;
            scaled_scores[index] = score;
            row_max = max(row_max, score);
        }
        row_max = simd_max_16(row_max);

        const float old_max = shared_stats[2 * softmax_row];
        const float old_sum = shared_stats[2 * softmax_row + 1];
        const bool block_valid = row_max != -INFINITY;
        const float next_max = block_valid ? max(old_max, row_max) : old_max;
        const float old_scale = old_sum == 0.0f
            ? 0.0f
            : (block_valid ? exp(old_max - next_max) : 1.0f);
        float block_sum = 0.0f;
#pragma unroll
        for (ushort index = 0; index < 4; ++index) {
            const ushort key_column = softmax_lane + 16 * index;
            const float probability = scaled_scores[index] == -INFINITY
                ? 0.0f
                : exp(scaled_scores[index] - next_max);
            shared_scores[softmax_row * key_tile + key_column] = probability;
            block_sum += probability;
        }
        block_sum = simd_sum_16(block_sum);
        for (ushort dim = softmax_lane; dim < head_dim; dim += 16) {
            shared_output[softmax_row * head_dim + dim] *= old_scale;
        }
        if (softmax_lane == 0 && row_valid) {
            shared_stats[2 * softmax_row] = next_max;
            shared_stats[2 * softmax_row + 1] =
                old_sum * old_scale + block_sum;
        }
        threadgroup_barrier(mem_flags::mem_threadgroup);

        simdgroup_float8x8 output_fragments[8];
#pragma unroll
        for (ushort output_block = 0; output_block < 8; ++output_block) {
            simdgroup_load(
                output_fragments[output_block],
                shared_output + simd_id * 64 + output_block * 8,
                head_dim, 0, false);
        }
        threadgroup float * value_stage = shared_stage + simd_id * 8 * 16;
        for (ushort key_block = 0; key_block < key_tile; key_block += 8) {
            simdgroup_float8x8 probability_fragment;
            simdgroup_load(
                probability_fragment, shared_scores + key_block,
                key_tile, 0, false);
            const int run_start = shared_runs[key_block / 8];
            const ulong value_run_offset =
                ulong(uint(max(run_start, 0))) * ulong(cache_row_size) +
                kv_head * head_dim + simd_id * 64;
#pragma unroll
            for (ushort output_block = 0; output_block < 8; ++output_block) {
                if (run_start >= 0) {
                    device const bfloat * value_run = value_cache_bf16 +
                        value_run_offset + output_block * 8;
                    simdgroup_bfloat8x8 value_fragment;
                    simdgroup_barrier(mem_flags::mem_none);
                    simdgroup_load(
                        value_fragment, value_run,
                        cache_row_size, 0, false);
                    simdgroup_barrier(mem_flags::mem_none);
                    simdgroup_multiply_accumulate(
                        output_fragments[output_block], probability_fragment,
                        value_fragment, output_fragments[output_block]);
                    continue;
                }
                for (ushort index = lane; index < 8 * 8; index += 32) {
                    const ushort key_row = index / 8;
                    const ushort output_column = index & 7;
                    const int slot = shared_slots[key_block + key_row];
                    value_stage[index] = slot >= 0
                        ? bf16_to_f32(value_cache[
                              ulong(uint(slot)) * ulong(cache_row_size) +
                              kv_head * head_dim +
                              simd_id * 64 + output_block * 8 + output_column])
                        : 0.0f;
                }
                simdgroup_barrier(mem_flags::mem_threadgroup);
                simdgroup_float8x8 value_fragment;
                simdgroup_load(value_fragment, value_stage, 8, 0, false);
                simdgroup_multiply_accumulate(
                    output_fragments[output_block], probability_fragment,
                    value_fragment, output_fragments[output_block]);
                simdgroup_barrier(mem_flags::mem_threadgroup);
            }
        }
#pragma unroll
        for (ushort output_block = 0; output_block < 8; ++output_block) {
            simdgroup_store(
                output_fragments[output_block],
                shared_output + simd_id * 64 + output_block * 8,
                head_dim, 0, false);
        }
        threadgroup_barrier(mem_flags::mem_threadgroup);
    }

    for (uint index = tid; index < query_tile * head_dim; index += 128) {
        const uint row = index / head_dim;
        const uint dim = index - row * head_dim;
        const uint attention_row = attention_row_start + row;
        if (attention_row < attention_rows) {
            const uint query_token = attention_row / heads_per_kv;
            const uint query_head =
                kv_head * heads_per_kv + attention_row % heads_per_kv;
            const float sum = shared_stats[2 * row + 1];
            output[(query_token * args.num_q_heads + query_head) * head_dim + dim] =
                sum == 0.0f ? 0.0f : shared_output[index] / sum;
        }
    }
}
